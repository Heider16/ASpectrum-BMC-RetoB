import pandas as pd
import matplotlib.pyplot as plt
from arch import arch_model

# 1. Cargar el archivo de datos oficiales
ruta_archivo = 'Concurso.xlsx'
df = pd.read_excel(ruta_archivo, sheet_name='datos oficiales')
print("Primeras filas de los datos cargados:")
print(df.head())

# 2. Identificar columnas numéricas, excluyendo 'Fecha' y columnas vacías
columnas_excluir = ['Fecha', 'Unnamed: 3']
indices = [col for col in df.columns if col not in columnas_excluir and pd.api.types.is_numeric_dtype(df[col])]

print(f"\nSe encontraron {len(indices)} índices para analizar: {indices}\n")

# 3. Lista para almacenar los resultados del modelo GARCH
resultados_lista = []

# 4. Bucle principal para procesar cada índice (Gráficas + GARCH + Consolidación)
for indice in indices:
    print("="*80)
    print(f"PROCESANDO ÍNDICE: {indice.upper()}")
    print("="*80)

    # Calcular diferencias limpiando valores nulos
    serie_original = df[indice]
    serie_diferenciada = serie_original.diff().dropna()

    # ---- GRÁFICAS ----
    plt.figure(figsize=(14, 5))

    # Gráfica de la serie original
    plt.subplot(1, 2, 1)
    plt.plot(df['Fecha'], serie_original, color='blue', label='Original')
    plt.title(f'{indice} - Serie Original')
    plt.xlabel('Fecha')
    plt.xticks(rotation=45)
    plt.legend()
    plt.grid(True, linestyle='--', alpha=0.5)

    # Gráfica de la serie diferenciada
    plt.subplot(1, 2, 2)
    plt.plot(df['Fecha'].iloc[1:], serie_diferenciada, color='orange', label='Diferenciada')
    plt.title(f'{indice} - Primeras Diferencias')
    plt.xlabel('Fecha')
    plt.xticks(rotation=45)
    plt.legend()
    plt.grid(True, linestyle='--', alpha=0.5)

    plt.tight_layout()
    plt.show()

    # ---- MODELO GARCH(1,1) ----
    try:
        modelo = arch_model(serie_diferenciada, mean='Constant', vol='GARCH', p=1, q=1)
        res = modelo.fit(disp='off')

        # Mostrar resumen en consola
        print(f"\nResultados del Modelo GARCH(1,1) para {indice}:")
        print(res.summary().tables[1])
        print(f"Log-Likelihood: {res.loglikelihood:.2f} | AIC: {res.aic:.2f} | BIC: {res.bic:.2f}\n")

        # Extraer parámetros para el consolidado
        params = res.params
        pvalues = res.pvalues

        datos_modelo = {
            'Índice': indice,
            'Media (mu)': params.get('mu', None),
            'p-valor (mu)': pvalues.get('mu', None),
            'Constante Volatilidad (omega)': params.get('omega', None),
            'p-valor (omega)': pvalues.get('omega', None),
            'ARCH (alpha[1])': params.get('alpha[1]', None),
            'p-valor (alpha[1])': pvalues.get('p-valor (alpha[1])', pvalues.get('alpha[1]', None)),
            'GARCH (beta[1])': params.get('beta[1]', None),
            'p-valor (beta[1])': pvalues.get('p-valor (beta[1])', pvalues.get('beta[1]', None)),
            'Alpha + Beta (Persistencia)': params.get('alpha[1]', 0) + params.get('beta[1]', 0),
            'Log-Likelihood': res.loglikelihood,
            'AIC': res.aic,
            'BIC': res.bic
        }
        resultados_lista.append(datos_modelo)
        print(f"✓ Métricas de {indice} guardadas correctamente.\n")

    except Exception as e:
        print(f"✗ No se pudo ajustar el modelo GARCH(1,1) para {indice}: {e}\n")

# 5. Consolidar y guardar todos los resultados en un archivo Excel local
if resultados_lista:
    df_resultados = pd.DataFrame(resultados_lista)
    ruta_guardado = 'Resultados_GARCH_Indices.xlsx'
    df_resultados.to_excel(ruta_guardado, index=False)
    print(f"\n¡Proceso completado con éxito! Archivo guardado en: {ruta_guardado}")