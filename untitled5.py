import pandas as pd
from arch import arch_model

# 1. Identificar columnas numéricas
columnas_excluir = ['Fecha', 'Unnamed: 3']
indices = [col for col in df.columns if col not in columnas_excluir and pd.api.types.is_numeric_dtype(df[col])]

# 2. Lista para almacenar los resultados de cada índice
resultados_lista = []

for indice in indices:
    serie_diferenciada = df[indice].diff().dropna()

    try:
        # Ajustar GARCH(1,1)
        modelo = arch_model(serie_diferenciada, mean='Constant', vol='GARCH', p=1, q=1)
        res = modelo.fit(disp='off')

        # Extraer coeficientes y p-valores
        params = res.params
        pvalues = res.pvalues

        # Guardar métricas en un diccionario estructurado
        datos_modelo = {
            'Índice': indice,
            'Media (mu)': params.get('mu', None),
            'p-valor (mu)': pvalues.get('mu', None),
            'Constante Volatilidad (omega)': params.get('omega', None),
            'p-valor (omega)': pvalues.get('omega', None),
            'ARCH (alpha[1])': params.get('alpha[1]', None),
            'p-valor (alpha[1])': pvalues.get('alpha[1]', None),
            'GARCH (beta[1])': params.get('beta[1]', None),
            'p-valor (beta[1])': pvalues.get('beta[1]', None),
            'Alpha + Beta (Persistencia)': params.get('alpha[1]', 0) + params.get('beta[1]', 0),
            'Log-Likelihood': res.loglikelihood,
            'AIC': res.aic,
            'BIC': res.bic
        }
        resultados_lista.append(datos_modelo)
        print(f"✓ Modelo GARCH procesado con éxito para: {indice}")
    except Exception as e:
        print(f"✗ Error al procesar {indice}: {e}")

# 3. Crear un DataFrame con todos los resultados consolidados
df_resultados = pd.DataFrame(resultados_lista)

# 4. Guardar en un archivo Excel en tu Google Drive
ruta_guardado = '/content/drive/MyDrive/Colab Notebooks/Resultados_GARCH_Indices.xlsx'
df_resultados.to_excel(ruta_guardado, index=False)

print(f"\n¡Proceso completado! Se han guardado los resultados en: {ruta_guardado}")
display(df_resultados.head())